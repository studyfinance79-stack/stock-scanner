def load_all_stocks():
    # If you have a local CSV file generated by your scanner script:
    csv_filename = "stocks.csv"  # Update to your actual CSV filename if needed
    if os.path.exists(csv_filename):
        return pd.read_csv(csv_filename)

    return None


