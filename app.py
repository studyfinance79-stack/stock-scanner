# 2. UNIVERSAL CELL BADGE FORMATTER
# -----------------------------------------------------------------------------
def format_cell_to_badge(cell_value):
    """Cleans raw string clutter and converts second lines into styled pill badges."""
    if pd.isna(cell_value):
        return ""

    cleaned = (
        str(cell_value)
        .replace("\\n", "\n")
        .replace("\r", "")
        .strip()
    )
    lines = [line.strip() for line in cleaned.split("\n") if line.strip()]

    if not lines:
        return ""

    value_part = lines[0]
    badge_part = lines[1] if len(lines) > 1 else ""

    badge_html = ""
    if badge_part:
        b_upper = badge_part.upper()
        if any(
            k in b_upper
            for k in [
                "STRONG BUY",
                "SPIKE",
            ]
        ):
            badge_class = "badge-purple"
        elif any(
            k in b_upper
            for k in [
                "BUY",
                "BULLISH",
                "UP",
                "STRONG",
                "YES",
            ]
        ):
            badge_class = "badge-green"
        elif any(
            k in b_upper
            for k in [
                "WEAK",
                "LOW VOL",
                "BEARISH",
                "NO",
            ]
        ):
            badge_class = "badge-red"
        else:
            badge_class = "badge-green"

        badge_html = f'<br><span class="badge {badge_class}">{badge_part}</span>'

    return f'<div class="cell-value">{value_part}</div>{badge_html}'


